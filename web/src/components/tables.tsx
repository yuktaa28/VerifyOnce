import { Link } from "react-router-dom";
import { documentLabel, fieldLabel, formatTime, actorLabel, imageQualityLine, showValue } from "../format";
import type { AuditEvent, Decision, Fact, ImageQuality, PossibleScheme, RuleOutcome } from "../types";
import { Alert, FactStatusBadge, SourceBadge, VerdictBadge, cx } from "./ui";

/** Per-fact results: value, confidence, status, where it came from, and why it is flagged. */
export function FactsTable({ facts, showDocument = false, caption }: { facts: Fact[]; showDocument?: boolean; caption?: string }) {
  if (!facts.length) return <p className="text-sm text-muted">No fields were read from this document.</p>;
  return (
    <div className="table-wrap">
      <table className="data-table">
        {caption ? <caption className="sr-only">{caption}</caption> : null}
        <thead>
          <tr>
            {showDocument ? <th scope="col">Document</th> : null}
            <th scope="col">Field</th>
            <th scope="col">Value</th>
            <th scope="col">Confidence</th>
            <th scope="col">Status</th>
            <th scope="col">Source</th>
            <th scope="col">Why flagged</th>
          </tr>
        </thead>
        <tbody>
          {facts.map((f) => (
            <tr key={f.fact_id}>
              {showDocument ? <td className="whitespace-nowrap">{documentLabel(f.document_type)}</td> : null}
              <td className="font-semibold whitespace-nowrap">{fieldLabel(f.field)}</td>
              <td className="whitespace-nowrap">{showValue(f.field, f.value)}</td>
              <td className="tabular-nums">{f.confidence.toFixed(2)}</td>
              <td>
                <FactStatusBadge status={f.verification_status} reviewedBy={f.reviewed_by} />
              </td>
              <td>
                <SourceBadge fact={f} />
              </td>
              <td className="min-w-[12rem] text-muted">{f.flag_reasons.length ? f.flag_reasons.join("; ") : "—"}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

const OUTCOME: Record<string, { label: string; cls: string }> = {
  pass: { label: "✓ pass", cls: "text-green-900" },
  fail: { label: "✕ fail", cls: "text-red-900" },
};

/** Each rule, the value found, the document it came from, and the result. */
export function RuleTable({ outcomes }: { outcomes: RuleOutcome[] }) {
  return (
    <div className="table-wrap">
      <table className="data-table">
        <caption className="sr-only">Rules checked</caption>
        <thead>
          <tr>
            <th scope="col">Rule</th>
            <th scope="col">Value found</th>
            <th scope="col">Source document</th>
            <th scope="col">Result</th>
          </tr>
        </thead>
        <tbody>
          {outcomes.map((o) => {
            const out = OUTCOME[o.outcome] ?? { label: "! unresolved", cls: "text-amber-950" };
            return (
              <tr key={o.rule_id}>
                <td className="min-w-[12rem]">
                  {o.requirement || `${o.field} ${o.operator} ${String(o.expected)}`}
                  <span className="mt-0.5 block font-mono text-xs text-muted">{o.rule_id}</span>
                </td>
                <td className="whitespace-nowrap">{showValue(o.field, o.actual)}</td>
                <td>{o.source_documents.map(documentLabel).join(", ") || "—"}</td>
                <td className={cx("font-semibold whitespace-nowrap", out.cls)}>
                  {out.label}
                  {o.evidence_issues.length ? <span className="block text-xs font-normal text-muted">{o.evidence_issues.join(", ")}</span> : null}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

export function ExplanationBox({ decision, officer = false }: { decision: Decision; officer?: boolean }) {
  const text = officer ? decision.officer_brief : decision.explanation;
  if (!text) return null;
  const label =
    decision.explanation_source === "generated"
      ? `Generated by ${decision.explanation_model || "the model"}; the verdict was decided by the rules.`
      : "Template explanation; the verdict was decided by the rules.";
  return (
    <div className="rounded-lg border border-line bg-paper p-4">
      <p className="font-semibold">{officer ? "Officer brief" : "In plain words"}</p>
      <p className="mt-1">{text}</p>
      <p className="mt-2 text-xs text-muted">{label}</p>
    </div>
  );
}

/** Verdict, reason and the rule table for one decision. */
export function DecisionCard({ decision, officer = false }: { decision: Decision; officer?: boolean }) {
  const tone = decision.verdict === "approve" ? "success" : decision.verdict === "reject" ? "error" : "warning";
  return (
    <div className="space-y-4">
      <Alert tone={tone} role="status">
        <div className="flex flex-wrap items-center gap-2">
          <VerdictBadge verdict={decision.verdict} />
          <span className="font-semibold">{decision.scheme_name}</span>
          <span className="text-sm text-muted">ruleset {decision.ruleset_version}</span>
        </div>
        <p className="mt-2">{decision.reason}</p>
      </Alert>
      {decision.review_reasons.length ? (
        <div>
          <h3 className="font-semibold">Why it needs an officer</h3>
          <ul className="mt-1 list-disc space-y-1 pl-5 text-[0.95rem]">
            {decision.review_reasons.map((r, i) => (
              <li key={i}>{r.message}</li>
            ))}
          </ul>
        </div>
      ) : null}
      <ExplanationBox decision={decision} officer={officer} />
      <div>
        <h3 className="mb-2 font-semibold">Rules checked</h3>
        <RuleTable outcomes={decision.rule_outcomes} />
      </div>
      <p className="text-xs text-muted">
        Decided by {actorLabel(decision.decided_by)} · {formatTime(decision.created_at)} · decision #{decision.decision_id}
        {decision.supersedes_decision_id ? ` (supersedes #${decision.supersedes_decision_id})` : ""}
      </p>
    </div>
  );
}

export function PossibleSchemes({
  schemes,
  onApply,
  busy,
}: {
  schemes: PossibleScheme[];
  onApply: (schemeId: string) => void;
  busy: string | null;
}) {
  const likely = schemes.filter((s) => s.predicted_verdict === "approve");
  if (!likely.length) return null;
  return (
    <section className="rounded-xl border border-green-700/30 bg-green-50 p-4" aria-labelledby="may-qualify">
      <h3 id="may-qualify" className="font-bold text-green-950">
        You may qualify for
      </h3>
      <p className="text-sm text-green-950">Using the documents already on file. No new upload needed.</p>
      <ul className="mt-3 space-y-3">
        {likely.map((s) => (
          <li key={s.scheme_id} className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
            <span className="text-[0.95rem] text-green-950">
              <strong>{s.scheme_name}</strong>: {s.reason}
            </span>
            <button type="button" className="btn btn-primary shrink-0" disabled={busy !== null} onClick={() => onApply(s.scheme_id)}>
              {busy === s.scheme_id ? "Applying…" : `Apply for ${s.scheme_name}`}
            </button>
          </li>
        ))}
      </ul>
    </section>
  );
}

export function ImageQualityTable({ documents }: { documents: { document_id: number; document_type: string; filename: string | null; image_quality: ImageQuality | null }[] }) {
  return (
    <div className="table-wrap">
      <table className="data-table">
        <caption className="sr-only">Image quality measured on each document</caption>
        <thead>
          <tr>
            <th scope="col">Document</th>
            <th scope="col">Sharpness</th>
            <th scope="col">Contrast</th>
            <th scope="col">Result</th>
          </tr>
        </thead>
        <tbody>
          {documents.map((d) => {
            const q = d.image_quality;
            const measured = q && q.sharpness !== undefined && q.contrast !== undefined;
            return (
              <tr key={d.document_id} className={q && !q.ok ? "bg-amber-50" : undefined}>
                <td className="whitespace-nowrap">
                  <span className="font-semibold">{documentLabel(d.document_type)}</span>
                  {d.filename ? <span className="block text-xs text-muted">{d.filename}</span> : null}
                </td>
                <td className="tabular-nums whitespace-nowrap">
                  {measured ? (
                    <Meter value={q.sharpness!} min={q.min_sharpness!} label="sharpness" />
                  ) : (
                    "—"
                  )}
                </td>
                <td className="tabular-nums whitespace-nowrap">
                  {measured ? <Meter value={q.contrast!} min={q.min_contrast!} label="contrast" /> : "—"}
                </td>
                <td className={cx("font-semibold whitespace-nowrap", q?.ok ? "text-green-900" : "text-red-900")}>
                  {!q ? "not measured" : q.ok ? "✓ ok" : "✕ blurry or low-contrast"}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
      <p className="mt-2 text-xs text-muted">Measured directly from the image, with no AI. A low-quality scan flags every field read from it.</p>
    </div>
  );
}

function Meter({ value, min, label }: { value: number; min: number; label: string }) {
  const ok = value >= min;
  return (
    <span className="inline-flex items-center gap-2">
      <span className={ok ? "text-ink" : "font-semibold text-red-900"}>{value.toFixed(1)}</span>
      <span className="text-xs text-muted">min {min}</span>
      <span className="sr-only">{ok ? `${label} passes` : `${label} below minimum`}</span>
    </span>
  );
}

export function QualityLine({ quality }: { quality: ImageQuality | null }) {
  const low = quality && !quality.ok;
  return <p className={cx("text-sm", low ? "font-semibold text-amber-950" : "text-muted")}>{imageQualityLine(quality)}</p>;
}

/** Audit history: every step with actor and time. Decisions are never edited, only superseded. */
export function AuditTimeline({ events }: { events: AuditEvent[] }) {
  if (!events.length) return <p className="text-sm text-muted">No events yet.</p>;
  return (
    <ol className="relative space-y-4 border-l-2 border-line pl-5">
      {events.map((e) => (
        <li key={e.audit_event_id} className="relative">
          <span
            className={cx(
              "absolute top-1.5 -left-[1.69rem] h-3 w-3 rounded-full border-2 border-white",
              e.actor.startsWith("officer:") ? "bg-accent" : "bg-[#6b7280]",
            )}
            aria-hidden="true"
          />
          <p className="text-[0.95rem] font-semibold text-ink">
            {e.summary}
            {e.is_original_decision ? <span className="ml-2 rounded bg-paper px-1.5 py-0.5 text-xs font-semibold text-muted">original</span> : null}
          </p>
          {e.reason ? <p className="mt-0.5 text-[0.95rem] text-ink">Reason: “{e.reason}”</p> : null}
          <p className="text-xs text-muted">
            {actorLabel(e.actor)} · <time dateTime={e.at}>{formatTime(e.at)}</time>
          </p>
        </li>
      ))}
    </ol>
  );
}

export function BackLink({ to, children }: { to: string; children: string }) {
  return (
    <Link to={to} className="inline-flex min-h-[44px] items-center gap-1 font-semibold text-accent underline-offset-4 hover:underline">
      <span aria-hidden="true">←</span> {children}
    </Link>
  );
}
